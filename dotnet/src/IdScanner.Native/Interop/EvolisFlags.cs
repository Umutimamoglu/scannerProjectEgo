    /// <summary>Bayrak kimliğinden ismini döndür.</summary>
    internal static string Name(int id) =>
        id >= 0 && id < Names.Length ? Names[id] : $"BILINMEYEN_{id}";

    /// <summary>
    /// Kullanıcıya gösterilmeye değer mi.
    ///
    /// RSV_ rezerve, CFG_ ise yazıcının sabit yapılandırması — ikisi de
    /// "şu an ne oluyor" sorusuna cevap vermez, durum satırını kalabalıklaştırır.
    /// Java'daki EvolisPrinter.readState() aynı elemeyi yapıyordu.
    /// </summary>
    internal static bool IsReportable(string name) =>
        !name.StartsWith("RSV_", StringComparison.Ordinal) &&
        !name.StartsWith("CFG_", StringComparison.Ordinal);
